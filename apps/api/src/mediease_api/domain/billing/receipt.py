"""The printed bill and receipt (M6d-P4; FR-BIL-04; spec billing R43-R54; B7).

One document shows an issued bill as it stands: its lines, the totals, every credit note, every
payment and refund (voided ones struck through) and the balance. It is laid out on the clinic's
letterhead and paper size, like a prescription, and holds nothing clinical: no diagnosis, no
visit note, no medicine (B3).

A bill changes after issue only by credit notes, payments and voids, and each of those moves its
``state`` forward. A receipt is rendered **once per state** and stored under that state's key
(``receipt_object_key``), so every download of one state is the same file. Text is English at
M6d; the patient's language comes with the receipt template review (spec billing R44).
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass
from uuid import UUID

from mediease_api.domain.billing.bill import Bill, BillStatus, DiscountKind
from mediease_api.domain.billing.payment import Payment, PaymentKind
from mediease_api.domain.clinics.clinic import Clinic, PaperSize
from mediease_api.domain.clinics.doctor import Doctor
from mediease_api.domain.patients.patient import Language, Patient
from mediease_api.domain.prescriptions.document import format_date, format_phone
from mediease_api.domain.shared.errors import DomainError

FOOTER = "Generated by MediEase. Keep this receipt for your records."
PAGE_LABEL = ("Page ", " of ", "")
MINUS = "\N{MINUS SIGN}"
_MODES = {"CASH": "Cash", "UPI": "UPI", "CARD": "Card"}


class ReceiptNotReady(DomainError):
    """R43: a draft has no receipt."""

    code = "BIL_RECEIPT_NOT_READY"

    def __init__(self) -> None:
        super().__init__("Issue the bill before printing it.")


def format_rupees(paise: int) -> str:
    """Indian grouping, two decimals: 12345678 -> '₹1,23,456.78'; negative with a minus."""
    sign = MINUS if paise < 0 else ""
    rupees, rest = divmod(abs(paise), 100)
    digits = str(rupees)
    if len(digits) > 3:
        head, tail = digits[:-3], digits[-3:]
        groups: list[str] = []
        while len(head) > 2:
            groups.insert(0, head[-2:])
            head = head[:-2]
        if head:
            groups.insert(0, head)
        digits = ",".join([*groups, tail])
    return f"{sign}₹{digits}.{rest:02d}"


def receipt_state(credit_notes: Sequence[Bill], payments: Sequence[Payment]) -> int:
    """R45: every change after issue moves this forward: a credit note, a payment, a void."""
    return len(credit_notes) + len(payments) + sum(1 for p in payments if p.is_voided)


def receipt_object_key(clinic_id: UUID, bill_id: UUID, state: int) -> str:
    return f"receipt/{clinic_id}/{bill_id}/s{state}.pdf"


@dataclass(frozen=True, slots=True)
class ReceiptLine:
    description: str
    quantity: int
    unit_price: str
    discount: str | None
    amount: str
    credited: bool


@dataclass(frozen=True, slots=True)
class ReceiptEntry:
    """A labelled row: a total, a credit note or a payment."""

    label: str
    value: str
    struck: bool = False


@dataclass(frozen=True, slots=True)
class ReceiptDocument:
    """Every word of the printed bill, decided before layout (the PDF adapter only lays out)."""

    # Read by the shared page stylesheet (adapters/pdf/assets/page.css.j2).
    language: Language
    paper_size: PaperSize
    footer: str
    page_label: tuple[str, str, str]
    title: str
    status_note: str | None
    clinic_name: str
    clinic_lines: tuple[str, ...]
    doctor_name: str | None
    number: str
    bill_date: str
    patient: tuple[ReceiptEntry, ...]
    lines: tuple[ReceiptLine, ...]
    totals: tuple[ReceiptEntry, ...]
    credit_notes: tuple[ReceiptEntry, ...]
    payments: tuple[ReceiptEntry, ...]
    balance: ReceiptEntry
    notes: str | None


def _discount_text(line_discount: int, share: int, kind: DiscountKind, value: int) -> str | None:
    total = line_discount + share
    if total == 0:
        return None
    if kind is DiscountKind.PERCENT and share == 0:
        return f"{MINUS} {format_rupees(total)} ({value / 100:g}%)"
    return f"{MINUS} {format_rupees(total)}"


def build_receipt(
    bill: Bill,
    *,
    credit_notes: Sequence[Bill],
    payments: Sequence[Payment],
    patient: Patient,
    doctor: Doctor | None,
    clinic: Clinic,
) -> ReceiptDocument:
    """R43-R47: the issued bill as it stands now."""
    if bill.status is BillStatus.DRAFT or bill.number is None or bill.bill_date is None:
        raise ReceiptNotReady()
    lang = Language.EN
    clinic_lines = tuple(
        line
        for line in (
            clinic.address_line,
            ", ".join(p for p in (clinic.city, clinic.state, clinic.pincode) if p) or None,
            f"Phone {format_phone(clinic.phone.e164)}" if clinic.phone else None,
        )
        if line
    )
    totals = [ReceiptEntry("Subtotal", format_rupees(bill.subtotal_paise))]
    if bill.discount_paise:
        totals.append(
            ReceiptEntry("Bill discount", f"{MINUS} {format_rupees(bill.discount_paise)}")
        )
    totals.append(ReceiptEntry("Total", format_rupees(bill.total_paise)))
    if bill.credited_paise:
        totals.append(ReceiptEntry("Credited", f"{MINUS} {format_rupees(bill.credited_paise)}"))
    if bill.paid_paise:
        totals.append(ReceiptEntry("Paid", f"{MINUS} {format_rupees(bill.paid_paise)}"))
    if bill.refunded_paise:
        totals.append(ReceiptEntry("Refunded", format_rupees(bill.refunded_paise)))
    balance = bill.balance_paise
    if balance > 0:
        due = ReceiptEntry("Balance due", format_rupees(balance))
    elif balance < 0:
        due = ReceiptEntry("To be refunded", format_rupees(-balance))
    else:
        due = ReceiptEntry("Balance", "Paid in full" if bill.paid_paise else format_rupees(0))
    return ReceiptDocument(
        language=lang,
        paper_size=clinic.rx_paper_size,
        footer=FOOTER,
        page_label=PAGE_LABEL,
        title=f"Bill {bill.number}",
        status_note="Cancelled: every line was credited."
        if bill.status is BillStatus.CANCELLED
        else None,
        clinic_name=clinic.name,
        clinic_lines=clinic_lines,
        doctor_name=doctor.display_name if doctor else None,
        number=bill.number,
        bill_date=format_date(bill.bill_date, lang),
        patient=(
            ReceiptEntry("Patient", patient.full_name),
            ReceiptEntry("Patient code", patient.code),
        ),
        lines=tuple(
            ReceiptLine(
                description=line.description,
                quantity=line.quantity,
                unit_price=format_rupees(line.unit_price_paise),
                discount=_discount_text(
                    line.discount_paise,
                    line.bill_discount_paise,
                    line.discount.kind,
                    line.discount.value,
                ),
                amount=format_rupees(line.amount_paise),
                credited=line.id in bill.credited_line_ids,
            )
            for line in bill.lines
        ),
        totals=tuple(totals),
        credit_notes=tuple(
            ReceiptEntry(
                f"Credit note {note.number} · {format_date(note.bill_date, lang)}"
                if note.bill_date
                else f"Credit note {note.number}",
                f"{MINUS} {format_rupees(note.total_paise)}",
            )
            for note in credit_notes
        ),
        payments=tuple(
            ReceiptEntry(
                f"{'Refund' if p.kind is PaymentKind.REFUND else 'Payment'} · "
                f"{_MODES[p.mode.value]} · {format_date(p.local_date, lang)}"
                + (f" · {p.reference}" if p.reference else "")
                + (" · voided" if p.is_voided else ""),
                format_rupees(p.amount_paise),
                struck=p.is_voided,
            )
            for p in payments
        ),
        balance=due,
        notes=bill.notes,
    )
